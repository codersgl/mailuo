/**
 * 搜索的纯逻辑：转义与两个上限。不碰数据库，可以单独测（与 domain/duration.ts 同一分工）。
 */

/** 搜索词长度上限。个人规划里没有比这更长的关键词，超了只可能是粘贴错了。 */
export const MAX_QUERY_LENGTH = 100;

/**
 * 单次搜索最多返回多少条。
 *
 * 它是结果列表的硬边界，不是「分页」：界面拿到 `truncated` 后提示「只显示前 N 条」，
 * 靠用户自己把词写具体。个人规模（几百个任务）下，翻页的复杂度换不来什么。
 */
export const SEARCH_LIMIT = 50;

/**
 * 把用户输入变成 `LIKE` 的 `%关键词%` 模式串，转义 `\`、`%`、`_`。
 *
 * 不转义就会有两种「结果比输入的多」的怪象：搜「100%」变成「以 100 开头」，
 * 搜「a_b」里的下划线匹配任意单字符。两种都看不出原因，所以按 SQLite 的规则转义。
 *
 * 一遍扫描同时处理三种字符：补进去的反斜杠不会被再转义一次。
 * 调用方的 SQL 必须写 `ESCAPE '\'`，否则反斜杠只是个普通字符，转义等于没做。
 */
export function toLikePattern(keyword: string): string {
  return `%${keyword.replace(/[\\%_]/g, (char) => `\\${char}`)}%`;
}
