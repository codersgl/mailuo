-- 004_duration_natural_day.sql：把工期的「1 天」从 480 分钟改成 1440 分钟（自然日）。
--
-- 为什么改：已用是按墙上时钟累计的（任务停在「进行中」列里就按 24 小时一天走），工期却按
-- 8 小时工作制折算，同一张卡片的分子与分母不是同一把尺子。实测一个「工期 7 天」的任务放置
-- 两天后进度条显示 66%（2210 / 3360），按自然日只有 22%——正好差 1440 / 480 = 3 倍。
-- 背景见 docs/decisions.md D80。
--
-- 存量数据按**用户当时输入的 天 / 小时 / 分**重新编码，而不是整体乘 3：
--   new = floor(old / 480) * 1440 + (old % 480)
-- 这样「7 天」仍是 7 天（3360 → 10080），「1 天 20 分」仍是「1 天 20 分」（500 → 1460），
-- 而整体乘 3 会把后者变成「3 天 20 分」。旧值经 CHECK 保证是非负整数，所以 SQLite 的整数相除
-- 在这个定义域里就是向下取整，与界面拆段的算法一致（负数才需要另行讨论，这里进不来）。
--
-- NULL（未估）与 0（瞬时）在原表达式下本来就是原值：WHERE 里那两条是**防御性**的，不是它们生效
-- 的原因。将来若有人放宽 duration_minutes 的 CHECK，负数进到 `%` 里时它才起作用。
--
-- **本文件不幂等**：同一条 UPDATE 再跑一次会把工期再放大一次（500 → 1460 → 4340）。
-- 只跑一次这件事由迁移 runner 的 schema_migrations 记账保证（见 apps/api/src/db/migrate.ts）。
--
-- 上界：旧上限是 9999 * 480 = 4799520，按本式映射到 9999 * 1440 = 14398560，正好是新上限；
-- 映射在非负整数上单调不减，所以迁移后没有任何一行超过新的 MAX_DURATION_MINUTES。
-- 溢出不用管：接口写入到不了那个量级，只有手工改库才可能（REAL 结果会撞 CHECK，整份迁移回滚）。

UPDATE tasks
   SET duration_minutes = (duration_minutes / 480) * 1440 + (duration_minutes % 480)
 WHERE duration_minutes IS NOT NULL
   AND duration_minutes > 0;
